"""
Required-payoff estimation error from gas-cost underestimation.

This script post-processes the event-level output produced by
run_gas_aware_replay.py. It does not rerun the historical price/gas replay.

Experiment
----------
For each baseline-feasible candidate, let

    K(q) = C(q) + R(q),

where C(q) is the true gas/execution cost and R(q) is the reservation payoff.

We impose relative gas-cost underestimation:

    C_hat(q) = (1 - alpha_K) C(q),
    K_hat(q) = C_hat(q) + R(q).

Hence the required-payoff error is

    e_K(q) = K(q) - K_hat(q) = alpha_K C(q).

We compare:
    1. delta = 0
    2. delta = e_K(q)               [pointwise covered]
or, optionally:
    2. delta = max_q e_K(q)         [global scalar bound]

The transfer rule is

    r(q) = min{
        lambda * S(q),
        max((1 - gamma) * (S(q) - K_hat(q)) - delta, 0)
    }.

Participation is always evaluated using the true quantities:

    S(q) - r(q) >= K(q).

Outputs
-------
- required_payoff_gas_error_events.csv
- required_payoff_gas_error_summary.csv
- required_payoff_gas_error_table.tex
- fig_required_payoff_gas_error.png

Typical usage
-------------
python run_required_payoff_gas_error.py \
    --events-csv results_gas_robustness/gas_robustness_events.csv \
    --gas-multiplier 1 \
    --alphas 0,0.10,0.25,0.50 \
    --lambda-value 0.75 \
    --gamma 0 \
    --buffer-mode pointwise
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Iterable

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd


# ---------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------

def parse_float_list(raw: str) -> list[float]:
    try:
        values = [float(x.strip()) for x in raw.split(",") if x.strip()]
    except ValueError as exc:
        raise argparse.ArgumentTypeError(
            f"Expected comma-separated floats, got: {raw}"
        ) from exc

    if not values:
        raise argparse.ArgumentTypeError("At least one value is required.")
    return values


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Evaluate required-payoff estimation error caused by "
            "gas-cost underestimation."
        )
    )

    parser.add_argument(
        "--events-csv",
        type=Path,
        default=Path("results/gas_robustness_events.csv"),
        help="Event-level CSV generated by run_gas_aware_replay.py",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path("results/required_payoff_gas_error"),
        help="Directory for outputs",
    )
    parser.add_argument(
        "--gas-multiplier",
        type=float,
        default=1.0,
        help=(
            "Select candidates from one gas_multiplier condition. "
            "Use 1 for the historical baseline gas-cost calibration."
        ),
    )
    parser.add_argument(
        "--alphas",
        type=parse_float_list,
        default=[0.0, 0.10, 0.25, 0.50],
        help=(
            "Comma-separated relative gas-cost underestimation levels, "
            "e.g. 0,0.10,0.25,0.50"
        ),
    )
    parser.add_argument(
        "--lambda-value",
        type=float,
        default=0.75,
        help="Surplus-sharing parameter lambda",
    )
    parser.add_argument(
        "--gamma",
        type=float,
        default=0.0,
        help=(
            "Retained-margin parameter gamma. Use 0 for the cleanest "
            "Theorem-3 safety-buffer test."
        ),
    )
    parser.add_argument(
        "--buffer-mode",
        choices=["pointwise", "global"],
        default="pointwise",
        help=(
            "pointwise: delta(q)=e_K(q); "
            "global: delta=max_q e_K(q) for every event."
        ),
    )
    parser.add_argument(
        "--rule-filter",
        default="baseline",
        help=(
            "If a rule column exists, prefer rows with this rule before "
            "deduplication. Default: baseline."
        ),
    )
    parser.add_argument(
        "--tolerance",
        type=float,
        default=1e-9,
        help="Relative numerical tolerance for participation tests",
    )

    return parser.parse_args()


# ---------------------------------------------------------------------
# Column resolution
# ---------------------------------------------------------------------

def first_existing(
    df: pd.DataFrame,
    candidates: Iterable[str],
    *,
    required: bool = True,
) -> str | None:
    for col in candidates:
        if col in df.columns:
            return col

    if required:
        raise KeyError(
            "Could not find any of the expected columns: "
            + ", ".join(candidates)
        )
    return None


def resolve_columns(df: pd.DataFrame) -> dict[str, str | None]:
    return {
        "surplus": first_existing(
            df,
            [
                "gross_surplus",
                "true_surplus",
                "surplus",
                "arbitrage_surplus",
            ],
        ),
        "execution_cost": first_existing(
            df,
            [
                "gas_cost",
                "gas_cost_usd",
                "execution_cost",
                "execution_cost_usd",
            ],
        ),
        "reservation": first_existing(
            df,
            [
                "reservation_profit",
                "reservation_payoff",
                "reservation",
            ],
        ),
        "baseline_feasible": first_existing(
            df,
            [
                "baseline_feasible",
                "is_baseline_feasible",
                "baseline_participates",
                "baseline_arbitrage",
            ],
        ),
        "gas_multiplier": first_existing(
            df,
            ["gas_multiplier"],
            required=False,
        ),
        "rule": first_existing(
            df,
            ["rule"],
            required=False,
        ),
        "lambda": first_existing(
            df,
            ["lambda", "lambda_value"],
            required=False,
        ),
        "gamma": first_existing(
            df,
            ["gamma"],
            required=False,
        ),
        "event_id": first_existing(
            df,
            [
                "event_id",
                "date",
                "datetime",
                "timestamp",
                "next_date",
            ],
            required=False,
        ),
        "lp_loss": first_existing(
            df,
            [
                "lp_loss_without_sharing",
                "lp_loss",
                "arbitrage_loss",
                "lp_arbitrage_loss",
            ],
            required=False,
        ),
    }


# ---------------------------------------------------------------------
# Candidate preparation
# ---------------------------------------------------------------------

def prepare_candidates(
    events: pd.DataFrame,
    *,
    gas_multiplier: float,
    rule_filter: str,
) -> tuple[pd.DataFrame, dict[str, str | None]]:
    cols = resolve_columns(events)
    df = events.copy()

    if cols["gas_multiplier"] is not None:
        gas_col = str(cols["gas_multiplier"])
        mask = np.isclose(
            pd.to_numeric(df[gas_col], errors="coerce"),
            gas_multiplier,
            rtol=1e-9,
            atol=1e-12,
        )
        df = df.loc[mask].copy()

        if df.empty:
            available = sorted(
                pd.to_numeric(
                    events[gas_col],
                    errors="coerce",
                ).dropna().unique()
            )
            raise ValueError(
                f"No rows found for gas_multiplier={gas_multiplier}. "
                f"Available values: {available}"
            )

    # Prefer baseline rows because the source file may repeat each candidate
    # for every sharing rule.
    if cols["rule"] is not None:
        rule_col = str(cols["rule"])
        baseline_rows = df[df[rule_col].astype(str) == rule_filter].copy()
        if not baseline_rows.empty:
            df = baseline_rows

    # If baseline rows are still repeated across lambda/gamma settings, remove
    # those duplicates using stable candidate identifiers where possible.
    dedupe_cols: list[str] = []

    if cols["event_id"] is not None:
        dedupe_cols.append(str(cols["event_id"]))

    # Keep gas multiplier in the key if it exists, although one value has
    # already been selected.
    if cols["gas_multiplier"] is not None:
        dedupe_cols.append(str(cols["gas_multiplier"]))

    # Add common identifying fields if present.
    for col in [
        "date",
        "next_date",
        "datetime",
        "timestamp",
        "initial_price",
        "reference_price",
        "tvlUSD",
        "tvl_usd",
    ]:
        if col in df.columns and col not in dedupe_cols:
            dedupe_cols.append(col)

    if dedupe_cols:
        df = df.drop_duplicates(subset=dedupe_cols, keep="first")
    else:
        # Fallback: deduplicate on the economic candidate quantities.
        fallback = [
            str(cols["surplus"]),
            str(cols["execution_cost"]),
            str(cols["reservation"]),
        ]
        df = df.drop_duplicates(subset=fallback, keep="first")

    surplus_col = str(cols["surplus"])
    cost_col = str(cols["execution_cost"])
    reservation_col = str(cols["reservation"])
    feasible_col = str(cols["baseline_feasible"])

    for col in [surplus_col, cost_col, reservation_col]:
        df[col] = pd.to_numeric(df[col], errors="coerce")

    df = df.dropna(
        subset=[surplus_col, cost_col, reservation_col, feasible_col]
    ).copy()

    feasible = df[feasible_col].astype(bool)
    df = df.loc[feasible].copy()

    if df.empty:
        raise ValueError("No baseline-feasible candidates remain.")

    df["true_surplus"] = df[surplus_col].astype(float)
    df["true_execution_cost"] = df[cost_col].astype(float)
    df["true_reservation_payoff"] = df[reservation_col].astype(float)
    df["true_required_payoff"] = (
        df["true_execution_cost"]
        + df["true_reservation_payoff"]
    )

    if (df["true_surplus"] < 0).any():
        raise ValueError("Negative true surplus found.")
    if (df["true_execution_cost"] < 0).any():
        raise ValueError("Negative execution cost found.")
    if (df["true_reservation_payoff"] < 0).any():
        raise ValueError("Negative reservation payoff found.")

    tol = 1e-9 * np.maximum(
        1.0,
        np.maximum(
            np.abs(df["true_surplus"]),
            np.abs(df["true_required_payoff"]),
        ),
    )

    inconsistent = (
        df["true_surplus"] + tol
        < df["true_required_payoff"]
    )

    if inconsistent.any():
        print(
            "WARNING: Dropping "
            f"{int(inconsistent.sum())} rows marked baseline-feasible "
            "but inconsistent with S >= C + R."
        )
        df = df.loc[~inconsistent].copy()

    if df.empty:
        raise ValueError(
            "No internally consistent baseline-feasible candidates remain."
        )

    return df.reset_index(drop=True), cols


# ---------------------------------------------------------------------
# Mechanism and evaluation
# ---------------------------------------------------------------------

def transfer_amount(
    *,
    surplus_hat: np.ndarray,
    required_payoff_hat: np.ndarray,
    delta: np.ndarray,
    lambda_value: float,
    gamma: float,
) -> np.ndarray:
    if not 0.0 <= lambda_value <= 1.0:
        raise ValueError("lambda_value must be in [0, 1].")
    if not 0.0 <= gamma < 1.0:
        raise ValueError("gamma must be in [0, 1).")

    proportional_cap = lambda_value * surplus_hat

    # Matches the convention used in the existing stale-oracle script:
    # (1-gamma)(S_hat-K_hat) - delta.
    participation_cap = np.maximum(
        (1.0 - gamma)
        * (surplus_hat - required_payoff_hat)
        - delta,
        0.0,
    )

    return np.minimum(proportional_cap, participation_cap)


def evaluate_experiment(
    candidates: pd.DataFrame,
    *,
    alphas: Iterable[float],
    lambda_value: float,
    gamma: float,
    buffer_mode: str,
    tolerance: float,
) -> tuple[pd.DataFrame, pd.DataFrame]:
    s_true = candidates["true_surplus"].to_numpy(dtype=float)
    c_true = candidates["true_execution_cost"].to_numpy(dtype=float)
    r_true = candidates["true_reservation_payoff"].to_numpy(dtype=float)
    k_true = candidates["true_required_payoff"].to_numpy(dtype=float)

    total_surplus = float(s_true.sum())
    if total_surplus <= 0:
        raise ValueError("Aggregate true surplus must be positive.")

    summary_rows: list[dict] = []
    event_frames: list[pd.DataFrame] = []

    for alpha in alphas:
        alpha = float(alpha)

        if not 0.0 <= alpha <= 1.0:
            raise ValueError(
                f"Each alpha must be in [0,1], got {alpha}."
            )

        c_hat = (1.0 - alpha) * c_true
        k_hat = c_hat + r_true
        e_k = k_true - k_hat  # exactly alpha * C(q)

        if buffer_mode == "pointwise":
            covered_delta = e_k
            covered_label = r"$\delta(q)=e_K(q)$"
            covered_scalar = np.nan
        elif buffer_mode == "global":
            epsilon_k = float(e_k.max())
            covered_delta = np.full_like(e_k, epsilon_k)
            covered_label = r"$\delta=\varepsilon_K$"
            covered_scalar = epsilon_k
        else:
            raise ValueError(f"Unknown buffer_mode: {buffer_mode}")

        variants = [
            (
                "unbuffered",
                r"$\delta=0$",
                np.zeros_like(e_k),
                0.0,
            ),
            (
                "covered",
                covered_label,
                covered_delta,
                covered_scalar,
            ),
        ]

        for variant, buffer_label, delta, delta_scalar in variants:
            transfer = transfer_amount(
                surplus_hat=s_true,
                required_payoff_hat=k_hat,
                delta=delta,
                lambda_value=lambda_value,
                gamma=gamma,
            )

            retained_true_payoff = s_true - transfer

            tol = tolerance * np.maximum(
                1.0,
                np.maximum(np.abs(k_true), np.abs(s_true)),
            )

            shortfall = np.maximum(
                k_true - retained_true_payoff,
                0.0,
            )
            violation = retained_true_payoff + tol < k_true

            event_out = candidates.copy()
            event_out["alpha_k"] = alpha
            event_out["variant"] = variant
            event_out["buffer_label"] = buffer_label
            event_out["estimated_execution_cost"] = c_hat
            event_out["estimated_required_payoff"] = k_hat
            event_out["required_payoff_error"] = e_k
            event_out["delta"] = delta
            event_out["transfer"] = transfer
            event_out["retained_true_payoff"] = retained_true_payoff
            event_out["participation_shortfall"] = shortfall
            event_out["participation_violation"] = violation
            event_frames.append(event_out)

            violation_count = int(violation.sum())
            total_transfer = float(transfer.sum())
            total_shortfall = float(shortfall.sum())

            if violation_count > 0:
                conditional_shortfall = float(shortfall[violation].mean())
                conditional_relative_shortfall = float(
                    np.mean(
                        shortfall[violation]
                        / np.maximum(k_true[violation], 1e-15)
                    )
                )
            else:
                conditional_shortfall = 0.0
                conditional_relative_shortfall = 0.0

            summary_rows.append(
                {
                    "alpha_k": alpha,
                    "gas_cost_underestimation_pct": 100.0 * alpha,
                    "variant": variant,
                    "buffer_label": buffer_label,
                    "buffer_mode": buffer_mode,
                    "delta_scalar": delta_scalar,
                    "n_candidates": len(candidates),
                    "num_violations": violation_count,
                    "participation_violation_rate": float(
                        violation.mean()
                    ),
                    "mean_shortfall_all_candidates": float(
                        shortfall.mean()
                    ),
                    "mean_shortfall_conditional_on_violation": (
                        conditional_shortfall
                    ),
                    "mean_relative_shortfall_conditional_on_violation": (
                        conditional_relative_shortfall
                    ),
                    "total_participation_shortfall": total_shortfall,
                    "aggregate_surplus_recapture_rate": (
                        total_transfer / total_surplus
                    ),
                    "total_transfer": total_transfer,
                    "total_true_surplus": total_surplus,
                    "mean_true_execution_cost": float(c_true.mean()),
                    "median_true_execution_cost": float(
                        np.median(c_true)
                    ),
                    "max_required_payoff_error": float(e_k.max()),
                    "mean_required_payoff_error": float(e_k.mean()),
                    "lambda": lambda_value,
                    "gamma": gamma,
                }
            )

    summary = pd.DataFrame(summary_rows).sort_values(
        ["alpha_k", "variant"],
        kind="stable",
    )
    events = pd.concat(event_frames, ignore_index=True)

    return summary.reset_index(drop=True), events


# ---------------------------------------------------------------------
# Output formatting
# ---------------------------------------------------------------------

def format_latex_table(summary: pd.DataFrame) -> str:
    table = summary[
        [
            "gas_cost_underestimation_pct",
            "buffer_label",
            "participation_violation_rate",
            "mean_shortfall_conditional_on_violation",
            "aggregate_surplus_recapture_rate",
        ]
    ].copy()

    table["participation_violation_rate"] *= 100.0
    table["aggregate_surplus_recapture_rate"] *= 100.0

    table = table.rename(
        columns={
            "gas_cost_underestimation_pct": (
                r"Gas-cost underestimation (\%)"
            ),
            "buffer_label": "Buffer",
            "participation_violation_rate": "Violations (\\%)",
            "mean_shortfall_conditional_on_violation": (
                "Mean shortfall (USD)"
            ),
            "aggregate_surplus_recapture_rate": "Recapture (\\%)",
        }
    )

    return table.to_latex(
        index=False,
        escape=False,
        float_format=lambda x: f"{x:.3f}",
        column_format="rcrrr",
    )


def plot_results(summary: pd.DataFrame, output_path: Path) -> None:
    fig, axes = plt.subplots(1, 3, figsize=(12.0, 3.2))

    styles = {
        "unbuffered": {
            "label": r"$\delta=0$",
            "linestyle": "--",
        },
        "covered": {
            "label": "Error-covered buffer",
            "linestyle": "-",
        },
    }

    metrics = [
        (
            "participation_violation_rate",
            "Participation violations (%)",
            100.0,
            "(a) Participation safety",
        ),
        (
            "mean_shortfall_conditional_on_violation",
            "Mean shortfall (USD)",
            1.0,
            "(b) Violation severity",
        ),
        (
            "aggregate_surplus_recapture_rate",
            "Surplus recapture (%)",
            100.0,
            "(c) Recovery trade-off",
        ),
    ]

    for ax, (metric, ylabel, scale, title) in zip(axes, metrics):
        for variant in ["unbuffered", "covered"]:
            d = summary[summary["variant"] == variant].sort_values(
                "gas_cost_underestimation_pct"
            )
            ax.plot(
                d["gas_cost_underestimation_pct"],
                scale * d[metric],
                marker="o",
                linestyle=styles[variant]["linestyle"],
                label=styles[variant]["label"],
            )

        ax.set_xlabel("Gas-cost underestimation (%)")
        ax.set_ylabel(ylabel)
        ax.set_title(title)
        ax.grid(True, alpha=0.3)

    axes[0].legend(frameon=False, fontsize=8)
    fig.tight_layout()
    fig.savefig(output_path, dpi=300, bbox_inches="tight")
    plt.close(fig)


# ---------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------

def main() -> None:
    args = parse_args()

    if not args.events_csv.exists():
        raise FileNotFoundError(
            f"Events CSV not found: {args.events_csv}"
        )

    args.output_dir.mkdir(parents=True, exist_ok=True)

    print(f"Loading events: {args.events_csv}")
    events = pd.read_csv(args.events_csv)

    candidates, cols = prepare_candidates(
        events,
        gas_multiplier=float(args.gas_multiplier),
        rule_filter=str(args.rule_filter),
    )

    print(f"Baseline-feasible candidates: {len(candidates):,}")
    print(
        "True execution cost: "
        f"mean={candidates['true_execution_cost'].mean():,.4f}, "
        f"median={candidates['true_execution_cost'].median():,.4f}, "
        f"max={candidates['true_execution_cost'].max():,.4f}"
    )
    print(
        "True required payoff: "
        f"mean={candidates['true_required_payoff'].mean():,.4f}, "
        f"median={candidates['true_required_payoff'].median():,.4f}, "
        f"max={candidates['true_required_payoff'].max():,.4f}"
    )

    summary, event_results = evaluate_experiment(
        candidates,
        alphas=args.alphas,
        lambda_value=float(args.lambda_value),
        gamma=float(args.gamma),
        buffer_mode=str(args.buffer_mode),
        tolerance=float(args.tolerance),
    )

    summary_path = (
        args.output_dir
        / "required_payoff_gas_error_summary.csv"
    )
    events_path = (
        args.output_dir
        / "required_payoff_gas_error_events.csv"
    )
    latex_path = (
        args.output_dir
        / "required_payoff_gas_error_table.tex"
    )
    figure_path = (
        args.output_dir
        / "fig_required_payoff_gas_error.png"
    )

    summary.to_csv(summary_path, index=False)
    event_results.to_csv(events_path, index=False)
    latex_path.write_text(
        format_latex_table(summary),
        encoding="utf-8",
    )
    plot_results(summary, figure_path)

    print()
    print(summary[
        [
            "gas_cost_underestimation_pct",
            "variant",
            "num_violations",
            "participation_violation_rate",
            "mean_shortfall_conditional_on_violation",
            "aggregate_surplus_recapture_rate",
            "max_required_payoff_error",
        ]
    ].to_string(index=False))

    print()
    print(f"Wrote: {summary_path}")
    print(f"Wrote: {events_path}")
    print(f"Wrote: {latex_path}")
    print(f"Wrote: {figure_path}")


if __name__ == "__main__":
    main()